<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;

/**
 * Generates the theme stylesheets the PANELS load (admin, instructor, student).
 *
 * The purchased theme forces its look with `!important` on colours, backgrounds, borders, spacing and type.
 * That makes a custom design system impossible to layer on top without a `!important` war, so for the panels we
 * serve a copy of the theme with those *visual* declarations demoted to normal priority. Structural declarations
 * (display, position, visibility, overflow, z-index…) keep their `!important`, because the theme's own JS toggles
 * rely on them. The public site keeps loading the untouched originals.
 *
 *   php artisan panel:build-theme            # regenerate
 *   php artisan panel:build-theme --check    # exit 1 if the generated files are stale (used by the test-suite)
 */
class BuildPanelTheme extends Command
{
    protected $signature = 'panel:build-theme {--check : Only verify that the generated files are up to date}';

    protected $description = 'Generate the panel copies of the theme CSS without visual !important';

    /** source (relative to public/) => generated file */
    public const FILES = [
        'admin/css/main.css' => 'css/vendor/theme-admin.css',
        'css/main.css' => 'css/vendor/theme-user.css',
    ];

    /** Declarations that must stay !important (behavioural, not visual). */
    private const KEEP = ['display', 'visibility', 'opacity', 'position', 'z-index', 'overflow', 'overflow-x', 'overflow-y', 'pointer-events', 'content', 'transform', 'transition', 'animation', 'flex-direction', 'float', 'clip', 'clip-path', 'top', 'left', 'right', 'bottom', 'inset'];

    public static function transform(string $css, string $source): string
    {
        $header = "/* GENERATED by `php artisan panel:build-theme` from public/{$source}. Do not edit: edit the source or panel.css. */\n";

        $body = preg_replace_callback('/([a-z-]+)\s*:\s*([^;{}]*?)\s*!important/i', function ($m) {
            return in_array(strtolower($m[1]), self::KEEP, true) ? $m[0] : $m[1] . ': ' . $m[2];
        }, $css);

        // The theme pins every table column to a fixed pixel width (th/td:nth-child(n)), which overflows any card narrower
        // than the sum. The panels let the browser size columns by content.
        $body = preg_replace_callback('/([^{}]+)\{([^{}]*)\}/', function ($m) {
            if (!preg_match('/(?:^|[\s>+~,])(?:th|td)(?::(?:nth-child|first-child|last-child|nth-of-type)|[\s,{])/i', $m[1] . ' ')) {
                return $m[0];
            }
            $decl = preg_replace('/(?<![\w-])(?:min-|max-)?width\s*:\s*[\d.]+px\s*(?:!important)?\s*;?/i', '', $m[2]);

            return $m[1] . '{' . $decl . '}';
        }, $body);
        // Rules left without declarations after the strip above are dead weight.
        $body = preg_replace('/(?<=[}\/])\s*[^{}@\/]+\{\s*\}/', '', $body);

        // The panels use the self-hosted Inter; never call Google Fonts from the dashboards.
        $body = preg_replace('~@import\s+url\(["\']?https?://fonts\.googleapis\.com[^;]*;~i', '', $body);

        return $header . self::rebaseUrls($body, $source, self::FILES[$source]);
    }

    /** url(../img/x.png) is relative to the source file; keep it pointing at the same asset from the generated file's folder. */
    private static function rebaseUrls(string $css, string $source, string $target): string
    {
        $norm = function (string $path): array {
            $out = [];
            foreach (explode('/', $path) as $seg) {
                if ($seg === '..') {
                    array_pop($out);
                } elseif ($seg !== '' && $seg !== '.') {
                    $out[] = $seg;
                }
            }

            return $out;
        };
        $srcDir = dirname($source);
        $dstDir = $norm(dirname($target));

        return preg_replace_callback('/url\(\s*([\'"]?)([^\'")]+)\1\s*\)/i', function ($m) use ($norm, $srcDir, $dstDir) {
            $u = $m[2];
            if (preg_match('~^(data:|https?:|//|/|#)~i', $u)) {
                return $m[0];
            }
            [$path, $suffix] = array_pad(preg_split('/(?=[?#])/', $u, 2), 2, '');
            $abs = $norm($srcDir . '/' . $path);
            $common = 0;
            while ($common < count($dstDir) && $common < count($abs) - 1 && $dstDir[$common] === $abs[$common]) {
                $common++;
            }
            $rel = str_repeat('../', count($dstDir) - $common) . implode('/', array_slice($abs, $common));

            return 'url(' . $m[1] . $rel . $suffix . $m[1] . ')';
        }, $css);
    }

    public function handle(): int
    {
        $stale = false;
        foreach (self::FILES as $source => $target) {
            $src = public_path($source);
            $dst = public_path($target);
            $out = self::transform(file_get_contents($src), $source);

            if ($this->option('check')) {
                if (!is_file($dst) || file_get_contents($dst) !== $out) {
                    $this->error("Stale: {$target}");
                    $stale = true;
                }
                continue;
            }

            @mkdir(dirname($dst), 0775, true);
            file_put_contents($dst, $out);
            $this->info(sprintf('%s  (%s -> %s)', $target, number_format(filesize($src)), number_format(strlen($out))));
        }

        return $stale ? self::FAILURE : self::SUCCESS;
    }
}
